/// Adds the two auth schemes (session cookie + bearer api key) to the
/// generated document.
pub struct SecurityAddon;

impl utoipa::Modify for SecurityAddon {
    fn modify(&self, openapi: &mut utoipa::openapi::OpenApi) {
        if let Some(components) = openapi.components.as_mut() {
            components.add_security_scheme(
                "session_cookie",
                SecurityScheme::Http(
                    HttpBuilder::new()
                        .scheme(HttpAuthScheme::Bearer)
                        .description(Some("Session cookie `vy_session` (obtained via login)."))
                        .build(),
                ),
            );
            components.add_security_scheme(
                "api_key",
                SecurityScheme::Http(
                    HttpBuilder::new()
                        .scheme(HttpAuthScheme::Bearer)
                        .description(Some("Headless API key: `Authorization: Bearer vy_...`."))
                        .build(),
                ),
            );
        }
    }
}
